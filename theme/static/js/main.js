/**
 * Module entry point.
 *
 * Three jobs, in this order:
 *   1. Read #site-data (the build's own JSON) and sanitise it.
 *   2. Wire the behaviour every page needs, each in its own try/catch so one
 *      broken feature cannot take the others with it.
 *   3. Load the expensive modules only when something actually asks for them:
 *      the palette on Ctrl+K or a button, the terminal on first open, the
 *      search index on the first keystroke, the matrix rain only if motion is
 *      allowed and the device looks willing.
 *
 * Nothing here is required for the page to be readable — the HTML is complete
 * on its own, and every selector below is an enhancement hook.
 */

import { qs, on, idle, safePath } from './modules/dom.js';
import { motionOK, onMotionChange } from './modules/motion.js';
import * as themes from './modules/theme.js';
import { init as initNav, toast } from './modules/nav.js';

const MATRIX_MIN_WIDTH = 720;

// -- site data ----------------------------------------------------------- //

const LANG = /^[a-z]{2,3}(?:-[A-Za-z]{2,4})?$/;
const NAME = /^[a-z][a-z0-9-]{1,15}$/;

function readData() {
  const node = document.getElementById('site-data');
  if (!node) return {};
  try {
    const parsed = JSON.parse(node.textContent ?? '{}');
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : {};
  } catch {
    // A malformed blob means a build bug, not a reason to break the page.
    return {};
  }
}

/**
 * The blob is generated by our own build, but it is still parsed JSON: treat it
 * as input and let nothing through that has not been checked, since these
 * values become URLs, attributes and text.
 */
function sanitise(raw) {
  const strings = {};
  if (raw.strings && typeof raw.strings === 'object') {
    for (const key of Object.keys(raw.strings)) {
      const value = raw.strings[key];
      if (typeof value === 'string' && value.length <= 200) strings[key] = value;
    }
  }
  const languages = Array.isArray(raw.languages)
    ? raw.languages
      .filter((entry) => entry && LANG.test(String(entry.code ?? '')) && safePath(String(entry.url ?? '')))
      .map((entry) => ({ code: String(entry.code), url: String(entry.url), native: String(entry.native ?? entry.code) }))
    : [];
  return {
    lang: LANG.test(String(raw.lang ?? '')) ? String(raw.lang) : 'es',
    section: /^[a-z0-9-]{0,32}$/.test(String(raw.section ?? '')) ? String(raw.section) : '',
    home: safePath(String(raw.home ?? '')) ? String(raw.home) : '/',
    searchIndex: safePath(String(raw.searchIndex ?? '')) ? String(raw.searchIndex) : '',
    fsIndex: safePath(String(raw.fsIndex ?? '')) ? String(raw.fsIndex) : '',
    themes: Array.isArray(raw.themes) ? raw.themes.filter((name) => NAME.test(String(name))).map(String) : [],
    defaultTheme: NAME.test(String(raw.defaultTheme ?? '')) ? String(raw.defaultTheme) : 'phosphor',
    handle: String(raw.handle ?? 'czr').slice(0, 32),
    languages,
    strings,
  };
}

const data = sanitise(readData());

/** Run one feature's setup; log and continue if it explodes. */
function safe(label, fn) {
  try {
    return fn();
  } catch (error) {
    if (typeof console !== 'undefined') console.error('[' + label + '] init failed:', error);
    return null;
  }
}

// -- lazy modules -------------------------------------------------------- //

let palettePromise = null;
let terminalPromise = null;
let matrixPromise = null;

function loadPalette() {
  if (!palettePromise) {
    palettePromise = import('./modules/palette.js')
      .then((module) => module.init(data, { openTerminal: () => openTerminal() }))
      .catch((error) => {
        if (typeof console !== 'undefined') console.error('palette failed to load:', error);
        return null;
      });
  }
  return palettePromise;
}

function loadTerminal() {
  if (!terminalPromise) {
    terminalPromise = import('./modules/terminal.js')
      .then((module) => module.init(data))
      .catch((error) => {
        if (typeof console !== 'undefined') console.error('terminal failed to load:', error);
        return null;
      });
  }
  return terminalPromise;
}

function loadMatrix() {
  if (!matrixPromise) {
    matrixPromise = import('./modules/matrix.js').catch(() => null);
  }
  return matrixPromise;
}

async function openPalette(trigger) {
  const palette = await loadPalette();
  palette?.toggle(trigger);
}

async function openTerminal(trigger) {
  const terminal = await loadTerminal();
  terminal?.toggle(trigger);
}

// -- always-on wiring ---------------------------------------------------- //

/** Same contract as safe(), for the modules that arrive as a promise. */
function feature(label, load) {
  try {
    load().catch((error) => {
      if (typeof console !== 'undefined') console.error('[' + label + '] failed:', error);
    });
  } catch (error) {
    if (typeof console !== 'undefined') console.error('[' + label + '] failed:', error);
  }
}

safe('theme', () => themes.init(data));
safe('nav', () => initNav(data));

// These are small, apply to nearly every page and only ever add behaviour to
// markup that already works, so they load right away — just not synchronously.
feature('code', () => import('./modules/code.js').then((module) => module.init(data)));
feature('gif', () => import('./modules/gif.js').then((module) => module.init()));
feature('glitch', () => import('./modules/glitch.js').then((module) => module.init()));

if (qs('[data-toc-link]') || qs('#reading-progress')) {
  feature('toc', () => import('./modules/toc.js').then((module) => module.init()));
}

if (qs('[data-filter]')) {
  feature('filters', () => import('./modules/filters.js').then((module) => module.init(data)));
}

if (qs('#search-form')) {
  // The dedicated search page is the one place the index is wanted eagerly.
  feature('search-page', () => import('./modules/search.js').then((module) => module.initPage(data)));
}

// -- shortcuts and actions ----------------------------------------------- //

function isTyping(target) {
  return target instanceof Element
    && target.closest('input, textarea, select, [contenteditable=""], [contenteditable="true"]') !== null;
}

on(document, 'keydown', (event) => {
  if (event.defaultPrevented) return;
  const key = event.key;

  if ((event.ctrlKey || event.metaKey) && (key === 'k' || key === 'K')) {
    event.preventDefault();
    openPalette();
    return;
  }
  if (event.ctrlKey || event.metaKey || event.altKey) return;

  // Bare-key shortcuts must never fire while someone is typing, including
  // inside the terminal itself — where a backtick is just a backtick.
  if (isTyping(event.target)) return;

  if (key === '`' || key === 'º') {
    event.preventDefault();
    openTerminal();
  } else if (key === '/') {
    event.preventDefault();
    openPalette();
  }
});

on(document, 'click', (event) => {
  const target = event.target;
  const trigger = target instanceof Element ? target.closest('[data-action]') : null;
  if (!trigger) return;
  const action = trigger.getAttribute('data-action');

  if (action === 'open-palette') {
    event.preventDefault();
    openPalette(trigger);
  } else if (action === 'open-terminal') {
    event.preventDefault();
    openTerminal(trigger);
  } else if (action === 'cycle-theme') {
    event.preventDefault();
    const name = safe('theme-cycle', () => themes.cycle());
    if (name) toast((data.strings.themeSwitch ?? 'theme') + ': ' + name);
  }
});

// -- decoration ---------------------------------------------------------- //

function maybeMatrix() {
  if (!motionOK() || window.innerWidth < MATRIX_MIN_WIDTH) return;
  const cores = navigator.hardwareConcurrency;
  if (typeof cores === 'number' && cores > 0 && cores <= 2) return;
  loadMatrix().then((module) => module?.init());
}

idle(() => safe('matrix', maybeMatrix));

// A visitor who turns effects back on mid-session should get the rain without
// reloading; the module is only fetched at that point, never before.
onMotionChange((allowed) => {
  if (allowed) safe('matrix', maybeMatrix);
});

// Cross-document view transitions are opt-in from CSS; all this does is tell
// the stylesheet the browser can do them.
if (typeof document.startViewTransition === 'function' || 'ViewTransition' in window) {
  document.documentElement.classList.add('has-view-transitions');
}

// -- service worker ------------------------------------------------------ //

if ('serviceWorker' in navigator && (location.protocol === 'https:' || location.hostname === 'localhost')) {
  idle(() => {
    navigator.serviceWorker.register('/sw.js', { scope: '/' }).catch(() => {
      /* No offline support is a degraded experience, not a broken one. */
    });
  }, 4000);
}
